#!/usr/bin/env node
// Render every index.html of a codebase-workflow site from manifests + the fixed template.
//   node build-site.mjs <site-root>
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join, posix } from 'node:path';
import { fileURLToPath } from 'node:url';
import { findProjects, loadManifest, coverage, readJson } from './lib/manifest.mjs';

const SKILL_DIR = join(dirname(fileURLToPath(import.meta.url)), '..');
const SITE = join(SKILL_DIR, 'templates', 'site');
const TEMPLATE = readFileSync(join(SITE, 'index.template.html'), 'utf8')
  .replace('/*@CSS*/', () => readFileSync(join(SITE, 'site.css'), 'utf8'))
  .replace('/*@JS*/', () => readFileSync(join(SITE, 'site.js'), 'utf8'));

const CRUMB_START = '<!--cw-crumb-->';
const CRUMB_END = '<!--/cw-crumb-->';
const CRUMB_CSS = '<style>.cw-crumb{display:flex;flex-wrap:wrap;align-items:center;gap:6px;padding:8px 16px;font:13px/1.4 system-ui,-apple-system,"Segoe UI",Roboto,sans-serif;color:inherit;background:rgba(127,127,127,.12);border-bottom:1px solid rgba(127,127,127,.25)}'
  + '.cw-crumb a{color:inherit;opacity:.8;text-decoration:none}.cw-crumb a:hover{opacity:1;text-decoration:underline}.cw-crumb span{opacity:.5}.cw-crumb b{font-weight:600}'
  + '.cw-crumb i{margin-left:auto;font-style:normal;display:flex;gap:8px}.cw-crumb i a{font-weight:600;border:1px solid rgba(127,127,127,.4);border-radius:6px;padding:1px 7px}</style>';

const LABELS = {
  type: {
    architecture: { vi: 'Kiến trúc', en: 'Architecture' }, workflow: { vi: 'Luồng', en: 'Workflow' },
    sequence: { vi: 'Tuần tự', en: 'Sequence' }, dataflow: { vi: 'Luồng dữ liệu', en: 'Data flow' },
    lifecycle: { vi: 'Vòng đời', en: 'Lifecycle' }, erd: { vi: 'ERD', en: 'ERD' }, class: { vi: 'Lớp', en: 'Class' },
    tree: { vi: 'Sơ đồ cây', en: 'Tree' }, timeline: { vi: 'Dòng thời gian', en: 'Timeline' },
    waterfall: { vi: 'Waterfall', en: 'Waterfall' }, explainer: { vi: 'Tổng quan', en: 'Explainer' },
    legacy: { vi: 'Bản cũ', en: 'Legacy' },
  },
  audience: {
    'end-user': { vi: 'Người dùng', en: 'End user' }, dev: { vi: 'Kỹ thuật', en: 'Developer' },
    both: { vi: 'Người dùng + Kỹ thuật', en: 'End user + Dev' },
  },
  open: { vi: 'Mở trang →', en: 'Open page →' },
  pages: { vi: 'trang', en: 'pages' },
  coverage: { vi: 'Độ phủ', en: 'Coverage' },
  source: { vi: 'Nguồn', en: 'Source' },
  updated: { vi: 'Cập nhật', en: 'Updated' },
  empty: { vi: 'Không có trang khớp.', en: 'No matching page.' },
  back: { vi: '← Về trang dự án', en: '← Back to project' },
  home: { vi: '← Tất cả dự án', en: '← All projects' },
  folder: { vi: 'Thư mục', en: 'Folder' },
  generated: { vi: 'Sinh tự động bởi codebase-workflow — không sửa tay.', en: 'Generated by codebase-workflow — do not edit by hand.' },
  siteTitle: { vi: 'Tài liệu kiến trúc & luồng nghiệp vụ', en: 'Architecture & workflow docs' },
  siteSummary: { vi: 'Mỗi dự án là một bộ sơ đồ: hành trình người dùng, kiến trúc, dữ liệu.', en: 'One set of diagrams per project: user journeys, architecture, data.' },
};

const root = process.argv[2];
if (!root) fail('usage: build-site.mjs <site-root>');

const projects = [];
const errors = [];
for (const dir of findProjects(root)) {
  const m = loadManifest(root, dir);
  errors.push(...m.errors);
  if (!m.errors.length) projects.push(m);
}
if (errors.length) fail(errors.join('\n'));

const written = [];
for (const p of projects) {
  const m = p.data;
  const inv = readJson(join(root, p.dir, 'src', 'inventory.json'), null);
  const exclusions = readJson(join(root, p.dir, 'src', 'coverage-exclusions.json'), []);
  p.coverage = inv ? coverage(inv, m.pages, exclusions) : null;

  write(join(root, p.dir, 'index.html'), renderProject(m, m.pages, '', p.coverage));

  // A folder holding more than one page gets its own index.
  const byFolder = new Map();
  for (const page of m.pages) {
    const folder = posix.dirname(firstFile(page));
    if (folder === '.') continue;
    if (!byFolder.has(folder)) byFolder.set(folder, []);
    byFolder.get(folder).push(page);
  }
  for (const [folder, pages] of byFolder) {
    if (pages.length > 1) write(join(root, p.dir, folder, 'index.html'), renderProject(m, pages, folder, null));
  }

  // Every published page gets a breadcrumb back to its folder and project index.
  for (const page of m.pages) {
    for (const [lang, file] of Object.entries(page.files)) {
      const path = join(root, p.dir, file);
      if (!existsSync(path)) continue;
      const folder = posix.dirname(file);
      const folderIndex = folder !== '.' && (byFolder.get(folder)?.length ?? 0) > 1;
      const html = readFileSync(path, 'utf8');
      const next = injectCrumb(html, crumb(m, page, lang, file, folderIndex));
      if (next !== html) write(path, next);
    }
  }
}
write(join(root, 'index.html'), renderRoot(projects, readJson(join(root, 'site.json'), {})));
write(join(root, '.nojekyll'), '');
console.log(`built ${written.length} file(s):\n` + written.map((f) => '  ' + f).join('\n'));

// ---------- rendering ----------

function renderProject(m, pages, folder, cov) {
  const langs = m.languages;
  const rel = (file) => (folder ? posix.relative(folder, file) : file);
  const up = folder ? '../'.repeat(folder.split('/').length) : '';
  const groups = m.groups.filter((g) => pages.some((p) => p.group === g.id));

  const nav = groups.map((g) => `
      <div class="nav-group"><h2>${t(g.title, langs)}</h2><ul>
${pages.filter((p) => p.group === g.id).map((p) => `        <li data-search="${searchText(p)}"><a data-page data-type="${p.type}" ${hrefs(p, rel)}><span class="dot"></span><span>${t(p.title, langs)}</span></a></li>`).join('\n')}
      </ul></div>`).join('');

  const main = `
    <header class="hero">
      <h1>${folder ? `${t(LABELS.folder, langs)} <code>${esc(folder)}/</code>` : t(m.title, langs)}</h1>
      ${m.summary && !folder ? `<p>${t(m.summary, langs)}</p>` : ''}
      <ul class="facts">
        <li><b>${pages.length}</b> ${t(LABELS.pages, langs)}</li>
        ${cov ? `<li>${t(LABELS.coverage, langs)}: <b>${cov.percent}%</b> (${cov.done}/${cov.total})</li>` : ''}
        ${m.source?.repo ? `<li>${t(LABELS.source, langs)}: <b>${esc(m.source.repo)}</b>${m.source.commit ? ` @ ${esc(m.source.commit.slice(0, 7))}` : ''}</li>` : ''}
        ${m.generatedAt ? `<li>${t(LABELS.updated, langs)}: <b>${esc(m.generatedAt.slice(0, 10))}</b></li>` : ''}
      </ul>
    </header>
${groups.map((g) => `
    <section class="group" id="g-${g.id}">
      <h2>${t(g.title, langs)}</h2>
      ${g.summary ? `<p>${t(g.summary, langs)}</p>` : ''}
      <div class="cards">
${pages.filter((p) => p.group === g.id).map((p) => card(p, rel, langs)).join('\n')}
      </div>
    </section>`).join('')}
    <p class="empty">${t(LABELS.empty, langs)}</p>`;

  const head = `${folder ? `<a class="crumb" href="${up}index.html">${t(LABELS.back, langs)}</a>` : `<a class="crumb" href="../index.html">${t(LABELS.home, langs)}</a>`}
      <p class="brand">${t(m.title, langs)}</p>`;

  return fill({ title: plain(m.title, langs) + (folder ? ` — ${folder}/` : ''), langs, head, nav, main, foot: footer(m, langs) });
}

function renderRoot(projects, site) {
  const langs = [...new Set(projects.flatMap((p) => p.data.languages))];
  if (!langs.length) langs.push('vi');
  const title = site.title ?? LABELS.siteTitle;
  const nav = `
      <div class="nav-group"><ul>
${projects.map((p) => `        <li data-search="${esc(plain(p.data.title, langs).toLowerCase())}"><a href="${p.dir}/index.html"><span class="dot"></span><span>${t(p.data.title, langs)}</span></a></li>`).join('\n')}
      </ul></div>`;
  const main = `
    <header class="hero">
      <h1>${t(title, langs)}</h1>
      <p>${t(site.summary ?? LABELS.siteSummary, langs)}</p>
    </header>
    <section class="group">
      <div class="cards">
${projects.map((p) => `        <article class="card" data-search="${esc(plain(p.data.title, langs).toLowerCase())}">
          <h3><a href="${p.dir}/index.html">${t(p.data.title, langs)}</a></h3>
          ${p.data.summary ? `<p>${t(p.data.summary, langs)}</p>` : '<p></p>'}
          <div class="badges"><span class="badge">${p.data.pages.length} ${t(LABELS.pages, langs)}</span>${p.coverage ? `<span class="badge">${t(LABELS.coverage, langs)} ${p.coverage.percent}%</span>` : ''}</div>
          <a class="open" href="${p.dir}/index.html">${t(LABELS.open, langs)}</a>
        </article>`).join('\n')}
      </div>
    </section>
    <p class="empty">${t(LABELS.empty, langs)}</p>`;
  return fill({ title: plain(title, langs), langs, head: `<p class="brand">${t(title, langs)}</p>`, nav, main, foot: t(LABELS.generated, langs) });
}

function card(p, rel, langs) {
  const avail = Object.keys(p.files).map((l) => l.toUpperCase()).join(' · ');
  return `        <article class="card" data-type="${p.type}" data-search="${searchText(p)}">
          <div class="badges"><span class="badge type">${t(LABELS.type[p.type], langs)}</span><span class="badge">${t(LABELS.audience[p.audience], langs)}</span></div>
          <h3><a data-page ${hrefs(p, rel)}>${t(p.title, langs)}</a></h3>
          <p>${t(p.summary, langs)}</p>
          <div class="badges"><a class="open" data-page ${hrefs(p, rel)}>${t(LABELS.open, langs)}</a><span class="langs">${avail}</span></div>
        </article>`;
}

function footer(m, langs) {
  const gen = m.generator ? Object.entries(m.generator).map(([k, v]) => `${esc(k)} ${esc(v)}`).join(' · ') : '';
  return `${t(LABELS.generated, langs)}${gen ? ` ${gen}` : ''}`;
}

function fill({ title, langs, head, nav, main, foot }) {
  return TEMPLATE
    .replace('<html lang="vi" data-lang="vi">', `<html lang="${langs[0]}" data-lang="${langs[0]}" data-langs="${langs.join(',')}">`)
    .replace('<!--@TITLE-->', () => esc(title))
    .replace('<!--@SIDE_HEAD-->', () => head)
    .replace('<!--@NAV-->', () => nav)
    .replace('<!--@MAIN-->', () => main)
    .replace('<!--@FOOT-->', () => foot);
}

// Breadcrumb bar for a page: project › group › page, plus links to the page in other languages.
function crumb(m, page, lang, file, folderIndex) {
  const up = '../'.repeat(file.split('/').length - 1);
  const pick = (text) => esc(text[lang] ?? Object.values(text)[0]);
  const group = m.groups.find((g) => g.id === page.group);
  const groupHref = folderIndex ? `index.html?lang=${lang}` : `${up}index.html?lang=${lang}#g-${page.group}`;
  const others = Object.entries(page.files).filter(([l]) => l !== lang)
    .map(([l, f]) => `<a href="${esc(posix.relative(posix.dirname(file), f))}" hreflang="${l}">${l.toUpperCase()}</a>`).join('');
  return `<nav class="cw-crumb" aria-label="Breadcrumb"><a href="${up}index.html?lang=${lang}">${pick(m.title)}</a><span>›</span>`
    + (group ? `<a href="${groupHref}">${pick(group.title)}</a><span>›</span>` : '')
    + `<b>${pick(page.title)}</b>${others ? `<i>${others}</i>` : ''}</nav>`;
}

// Idempotent: replaces a previous breadcrumb, otherwise inserts right after <body>.
function injectCrumb(html, nav) {
  const block = `${CRUMB_START}${CRUMB_CSS}${nav}${CRUMB_END}`;
  const start = html.indexOf(CRUMB_START);
  if (start >= 0) {
    const end = html.indexOf(CRUMB_END, start) + CRUMB_END.length;
    return html.slice(0, start) + block + html.slice(end);
  }
  const body = html.match(/<body[^>]*>/i);
  if (!body) return html;
  const at = body.index + body[0].length;
  return html.slice(0, at) + block + html.slice(at);
}

// ---------- helpers ----------

function firstFile(p) {
  return Object.values(p.files)[0];
}

function hrefs(p, rel) {
  const entries = Object.entries(p.files);
  return `href="${esc(rel(entries[0][1]))}" ` + entries.map(([l, f]) => `data-href-${l}="${esc(rel(f))}"`).join(' ');
}

// One span per site language; a missing translation falls back to any available text.
function t(text, langs) {
  if (!text) return '';
  const any = Object.values(text)[0];
  if (langs.length === 1) return esc(text[langs[0]] ?? any);
  return langs.map((l) => `<span data-l="${l}">${esc(text[l] ?? any)}</span>`).join('');
}

function plain(text, langs) {
  return text[langs[0]] ?? Object.values(text)[0];
}

function searchText(p) {
  return esc([...Object.values(p.title), ...Object.values(p.summary), p.type, p.audience].join(' ').toLowerCase());
}

function esc(s) {
  return String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
}

function write(path, content) {
  writeFileSync(path, content);
  written.push(path);
}

function fail(msg) {
  console.error(`error: ${msg}`);
  process.exit(1);
}
